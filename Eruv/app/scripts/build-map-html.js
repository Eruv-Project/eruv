// Inlines assets/leaflet/map.html into src/components/mapHtml.generated.ts so the
// WebView can load it as a string (no asset download or extra native config).
// Run with `npm run build:map` after editing map.html; __tests__/mapHtml.test.ts
// fails while the two differ.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'assets/leaflet/map.html'), 'utf8').replace(/\r\n/g, '\n');
const out = `// GENERATED by scripts/build-map-html.js from assets/leaflet/map.html. Do not edit.\nexport const MAP_HTML = ${JSON.stringify(html)};\n`;
fs.writeFileSync(path.join(root, 'src/components/mapHtml.generated.ts'), out);
